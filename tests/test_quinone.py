def can_smi(smi):
    m = MolFromSmiles(smi)
    if m is None:
        return ""
    RemoveStereochemistry(m)

    return MolToSmiles(m)  # type: ignore


def can_mol(m):
    if m is None:
        return ""
    RemoveStereochemistry(m)

    return MolToSmiles(m)  # type: ignore


@pytest.mark.parametrize(
    "reactant, product, site",
    argvalues=[x[1:] for x in examples],
    ids=[x[0] for x in examples],
)
def test_quinone(product, reactant, site):
    if reactant == (
        "CN1CCOc2c1cc(cc2)Nc1ncc2n(n1)c(cc2)c1cccc(c1)S(=O)(=O)NC(C)(C)C"
    ):
        pytest.xfail(
            "Quinone formation does not open the fused N-alkyl oxazine ring"
        )

    canonical_product = can_smi(product)
    r = MolFromSmiles(reactant)
    RemoveStereochemistry(r)

    for _, mols in QuinoneFormation().metabolites(r):
        for p in mols:
            predicted = MolToSmiles(p)
            if predicted and canonical_product == can_smi(predicted):
                return  # success

    assert False, f"Failed to find {product} in {reactant}"
